// Writes packages/tokens/src/tokens.css, the palette as Tailwind theme variables for the landing
// page (apps/web), from the same `color` object the iPhone app reads (D031):
//   bun packages/tokens/scripts/emit-css.ts          # write it
//   bun packages/tokens/scripts/emit-css.ts --check  # fail if it is stale (part of `bun run check`)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { color } from "../src/color";

const OUT = fileURLToPath(new URL("../src/tokens.css", import.meta.url));

const kebab = (key: string) =>
  key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const lines: string[] = [];
for (const [group, value] of Object.entries(color)) {
  if (typeof value === "string") {
    lines.push(`  --color-${kebab(group)}: ${value.toLowerCase()};`);
    continue;
  }
  for (const [name, hex] of Object.entries(value)) {
    lines.push(
      `  --color-${kebab(group)}-${kebab(name)}: ${hex.toLowerCase()};`
    );
  }
}

const css = `/* Generated by packages/tokens/scripts/emit-css.ts from src/color.ts. Do not edit. */\n@theme {\n${lines.join("\n")}\n}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // absent reads as stale
  }
  if (current !== css) {
    console.error(
      "tokens.css is stale: run bun packages/tokens/scripts/emit-css.ts"
    );
    process.exit(1);
  }
  console.log("tokens.css: up to date");
} else {
  writeFileSync(OUT, css);
  console.log("tokens.css: written");
}
