// Regenerates packages/shared/src/legal/privacy-source.ts from docs/legal/PRIVACY.md (D029):
//   bun scripts/render-privacy.ts
// Every server (apps/api) and the landing (apps/web) render it at /privacy; apps/api/src/legal/privacy.test.ts fails when
// the two differ, so an edited policy cannot ship without being regenerated.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = readFileSync(resolve(root, "docs/legal/PRIVACY.md"), "utf8");
writeFileSync(
  resolve(root, "packages/shared/src/legal/privacy-source.ts"),
  `// Generated by scripts/render-privacy.ts from docs/legal/PRIVACY.md. Do not edit.\nexport const PRIVACY_MARKDOWN =\n  ${JSON.stringify(source)};\n`
);
console.log(
  "render-privacy: wrote packages/shared/src/legal/privacy-source.ts"
);
